// ============================================================================
// 13. レポート構成指示
// ============================================================================

export function generateStructurePrompt(
  reportSections: string[],
  hasGSN: boolean,
  stakeholder?: Stakeholder,
  structureDescription?: string
): string {
  const role = stakeholder?.role || 'Safety Engineer';
  // hicase由来の見出し（"1", "2.1", "2.1.1" 等の階層採番を既に含む）はそのまま使用し、
  // 二重採番を避ける。静的テンプレート由来の見出し（採番なし）は従来通り連番を付与する。
  const sectionsFormatted = reportSections.map((section, index) =>
    /^\d+(\.\d+)*\s/.test(section) ? `\n${section}` : `\n${index + 1}. ${section}`
  ).join('');

  let prompt = `
## レポート構成
以下の構成でSSRを作成してください：
${sectionsFormatted}`;

  if (hasGSN) {
    prompt += isExecutiveRole(role)
      ? '\n\n注意: GSN分析は1ページ以内で簡潔にまとめること。'
      : '\n\n注意: GSNファイルが含まれているため、GSN分析セクションを含めること。';

    // hicase由来の見出しは "2.1 S1: ..." のように階層採番が先頭に付くため、
    // ノードIDが文字列の先頭ではなく採番の後に来る形式も検出する。
    const hasNodeIdSections = reportSections.some(s =>
      /^[GSCASEJUsn]\d/.test(s) || /^\d+(\.\d+)*\s+[GSCASEJUsn]\d/.test(s)
    );
    if (hasNodeIdSections) {
      prompt += `

### GSNノード別セクションの記述指針

本レポートの主要セクションはGSN木構造のノードを見出しとして構成される。
各セクションではそのノードが示す安全論証の要素を中心に記述すること。

**Goalノード（G〜）— 安全目標**
- このゴールが主張する安全性の内容と対象スコープ
- 達成状況（達成/部分達成/未達成）とその判断根拠（エビデンス参照必須）
- 支持する下位ノード（SubGoal・Strategy・Evidence）への参照
- 未解決の課題・論証ギャップ（文書記載がある場合のみ）

**SubGoalノード — 具体的安全目標**
- 親ゴールとの関係・細分化の意図
- 達成状況と支持するエビデンス
- 残存課題（文書記載がある場合のみ）

**Strategyノード（S〜）— 論証戦略**
- 親ゴールをどのように分解・論証するかの方針と妥当性
- 戦略の網羅性評価（分解漏れがないか）
- 関連するContextやAssumptionとの関係

**Contextノード（C〜）/ Assumptionノード（A〜）— 前提条件**
- 前提の内容・適用範囲
- 前提の成立状況・有効性評価（文書記載がある場合のみ）
- 前提が崩れた場合の安全論証への影響

**Solutionノード（Sn〜）/ Evidenceノード（E〜）— 解決策・証拠**
- 証拠の種類（テスト結果、解析結果、レビュー記録等）と強度
- カバレッジと限界（何を証明し、何を証明していないか）
- 未完了の場合の完了予定・代替措置（文書記載がある場合のみ）

各ノードIDの意味: G=Goal（安全目標）、S=Strategy（論証戦略）、C=Context（前提コンテキスト）、A=Assumption（前提仮定）、Sn=Solution/Evidence（解決策/エビデンス）、U=Undeveloped（未開発）

### 見出しの記述形式（厳守）
- 見出し（\`##\`/\`###\`行）にノードID（G1, G1.1, S2, Sn3 等）やその後のコロンをそのまま記述してはならない。上記の構成一覧はノード対応を示す内部参照であり、見出しテキストとして転記しないこと。
- 見出しに残すのは章番号（1. / 1.1 等）のみとし、ノードIDの代わりにノードの内容を要約した体言止めの名詞句を記載すること。
- 見出しは体言止め（名詞句）で記述し、「〜する」「〜できる」「〜である」等の述語で終わる文章体にしないこと。
- 例:
  - 誤: \`## 1. G1: ブレーキシステムは衝突時に乗員を保護する\`
  - 正: \`## 1. 衝突時における乗員保護（ブレーキシステム）\`
- ノードIDへの言及が必要な場合は本文中で行い、見出しには含めないこと。

### 見出し末尾のマーカーの意味（hicase構成）
上記構成の一部の見出しには末尾に以下のマーカーが付与されている。これはステークホルダーの役職に応じて安全論証の展開粒度を調整した結果であり、必ず反映すること:
- \`[要約のみ]\`: この見出しの配下は展開せず、1段落の要約のみで記述し、それ以上の下位見出しを作らないこと。
- \`[Mandatory Core]\`: 役職に関わらず全レポート共通で必須の安全項目。省略しないこと。
- \`[Mandatory Core - 強制開放]\`: 本来はこの役職の展開設定では見出しにならない項目だが、必須安全項目であるため例外的に見出しとして開かれている。省略せず本文に反映すること。
- \`⚠ mandatory core: ...\`という注記がある見出しは、配下に隠れている必須安全項目の圧縮要約（件数または1文）である。この注記の内容を要約文中に必ず反映すること。`;
    }
  }

  if (structureDescription) {
    prompt += `\n\n構成説明: ${structureDescription.slice(0, 500)}`;
  }

  const hasNodeIdSectionsForRule = reportSections.some(s =>
    /^[GSCASEJUsn]\d/.test(s) || /^\d+(\.\d+)*\s+[GSCASEJUsn]\d/.test(s)
  );

  if (hasNodeIdSectionsForRule) {
    prompt += `

### 構成遵守ルール（厳守）【GSN由来レポート】
- **上記の構成に記載されたセクションのみを作成すること**
- 以下のセクションをはじめ、上記一覧にないセクションを独自に追加することは絶対に禁止する:
  - エグゼクティブサマリー / Executive Summary
  - リスク分析 / Risk Analysis
  - 推奨事項 / Recommendations
  - まとめ・結論 / Conclusion / Summary
  - テスト結果 / Test Results
  - 改善提案 / Improvement Proposals
  - GSN概要 / GSN分析 / GSN Analysis（独立セクションとして）
  - トレーサビリティ分析、用語集、参考文献一覧等
- 各GSNノードセクションの中でリスク・評価・推奨事項・エビデンスを記述すること
- 章番号は上記の番号に厳密に従うこと
- セクションの順序を入れ替えないこと
- 付録は禁止（GSN由来レポートでは付録セクションを設けない）`;
  } else {
    prompt += `

### 構成遵守ルール（厳守）
- **上記の構成に記載されたセクションのみを作成すること**
- 上記にないセクション（例: トレーサビリティ分析、用語集、参考文献一覧等）を独自に追加することは禁止する
- 各セクションの章番号は上記の番号に厳密に従うこと
- セクションの順序を入れ替えないこと
- ただし「付録」は、略語一覧や参照文書一覧など読者の理解を補助する情報がある場合に限り、最終章の後に追加してよい`;
  }

  prompt += `

### その他の注意事項
- 「根本原因分析」「5 Whys分析」等のセクションは、文書に原因分析の記録がある場合のみ含める（ハルシネーション防止規則第2項参照）`;

  return prompt;
}

// ============================================================================
// 14. 完全なユーザープロンプトの組み立て（v5更新）
// ============================================================================

export function buildCompleteUserPrompt(params: {
  stakeholder: Stakeholder;
  strategy: RhetoricStrategy;
  contextContent: string;
  reportSections: string[];
  hasGSN: boolean;
  structureDescription?: string;
  hasMandatoryCore?: boolean;
}): string {
  const {
    stakeholder,
    strategy,
    contextContent,
    reportSections,
    hasGSN,
    structureDescription,
    hasMandatoryCore = hasGSN,
  } = params;

  // プロンプトの組み立て順序（重要度順・重複なし）
  // 注: 役割定義（generateSystemPrompt）はAPIのsystemパラメータで渡すため除外
  const parts = [
    // 1. ハルシネーション防止 + 忠実性・整合性（唯一の権威的ソース）
    generateAntiHallucinationPrompt(stakeholder),

    // 3. 出力制約（フォーマット・文体・分量）
    generateOutputConstraints(stakeholder),

    // 4. 冗長防止規則 + 情報密度最適化
    generateRedundancyPreventionPrompt(stakeholder),

    // 5. 文書活用原則（引用ルール・網羅性・定量化を統合）
    generateDocumentUsagePrinciples(),

    // 6. ステークホルダー固有設定
    generateStakeholderSection(stakeholder, strategy),

    // 7. レポートガイドライン + 用語・平易表現（統合済み）
    generateReportGuidelines(stakeholder),

    // 8. コンテンツ生成ガイド
    generateGSNAnalysisPrompt(hasGSN, stakeholder),
    generateFigureRequirementsPrompt(hasGSN, stakeholder),
    generateRiskAnalysisPrompt(),

    // 8b. Mandatory Safety Core（GSNがある場合は全ステークホルダーに適用）
    generateMandatoryCorePrompt(hasMandatoryCore),

    // 9. 不適切ファイル対応（参考）
    generateInvalidFileGuidelines(),

    // 10. レトリック戦略
    `\n※ 以下の戦略を活かしつつ、ハルシネーション防止規則（第2項）を遵守すること。
${strategy}の特徴：${getStrategyGuidelines(strategy)}`,

    // 11. 提供文書
    `\n## 提供された文書の内容\n${contextContent}`,

    // 12. 構成指示
    generateStructurePrompt(reportSections, hasGSN, stakeholder, structureDescription)
  ];

  return parts.filter(p => p && p.trim().length > 0).join('\n');
}